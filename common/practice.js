    function pie(n, k) {
        let s = '<svg class="pr-shape" viewBox="-52 -52 104 104" aria-hidden="true">';
        for (let i = 0; i < n; i++) {
            const a0 = (i / n) * 2 * Math.PI - Math.PI / 2, a1 = ((i + 1) / n) * 2 * Math.PI - Math.PI / 2;
            s += `<path d="M0 0 L${(50 * Math.cos(a0)).toFixed(2)} ${(50 * Math.sin(a0)).toFixed(2)} A50 50 0 0 1 ${(50 * Math.cos(a1)).toFixed(2)} ${(50 * Math.sin(a1)).toFixed(2)} Z" class="${i < k ? "on" : "off"}"/>`;
        }
        return s + "</svg>";
    }

    function bar(n, k) {
        let s = `<svg class="pr-shape wide" viewBox="-2 -2 ${n * 20 + 4} 64" aria-hidden="true">`;
        for (let i = 0; i < n; i++) s += `<rect x="${i * 20}" y="0" width="20" height="60" class="${i < k ? "on" : "off"}"/>`;
        return s + "</svg>";
    }

